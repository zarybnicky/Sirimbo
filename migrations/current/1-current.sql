do $$
begin
  if not exists (select 1 from pg_catalog.pg_type where typname = 'document_kind') then
    create type document_kind as enum ('plan', 'evaluation');
  end if;
  if not exists (select 1 from pg_catalog.pg_type where typname = 'document_list_type') then
    create type document_list_type as enum ('bullet', 'ordered');
  end if;
end
$$;

create table if not exists document (
  id bigint primary key generated by default as identity,
  tenant_id bigint not null default current_tenant_id(),
  kind document_kind not null default 'plan',
  title text,
  created_by bigint default current_user_id(),
  event_instance_id bigint,
  event_series_id bigint,
  cohort_id bigint,
  show_to_members boolean not null default false,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),

  constraint document_tenant_id_id_key unique (tenant_id, id),
  constraint document_subject_check
    check (num_nonnulls(event_instance_id, event_series_id, cohort_id) = 1),

  foreign key (tenant_id) references tenant (id) on delete cascade,
  foreign key (created_by) references users (id) on delete set null,
  foreign key (tenant_id, event_instance_id)
    references event_instance (tenant_id, id) on delete cascade,
  foreign key (tenant_id, event_series_id)
    references event_series (tenant_id, id) on delete cascade,
  foreign key (tenant_id, cohort_id)
    references cohort (tenant_id, id) on delete cascade
);

create table if not exists document_node (
  id uuid primary key default uuidv7(),
  tenant_id bigint not null default current_tenant_id(),
  document_id bigint not null,
  parent_id uuid,
  ordering numeric not null default 1,
  list_type document_list_type not null default 'bullet',
  content jsonb not null default '{"type":"paragraph","content":[]}'::jsonb,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),

  constraint document_node_tenant_id_id_key unique (tenant_id, id),
  constraint document_node_tenant_document_id_key unique (tenant_id, document_id, id),
  constraint document_node_parent_not_self check (parent_id is null or parent_id <> id),

  foreign key (tenant_id) references tenant (id) on delete cascade,
  foreign key (tenant_id, document_id)
    references document (tenant_id, id) on delete cascade,
  foreign key (tenant_id, document_id, parent_id)
    references document_node (tenant_id, document_id, id) on delete cascade
);

create table if not exists document_node_tag (
  id bigint primary key generated by default as identity,
  tenant_id bigint not null default current_tenant_id(),
  node_id uuid not null,
  person_id bigint,
  couple_id bigint,
  cohort_id bigint,
  created_at timestamp with time zone not null default now(),

  constraint document_node_tag_target_check
    check (num_nonnulls(person_id, couple_id, cohort_id) = 1),
  constraint document_node_tag_unique
    unique nulls not distinct (node_id, person_id, couple_id, cohort_id),

  foreign key (tenant_id) references tenant (id) on delete cascade,
  foreign key (tenant_id, node_id)
    references document_node (tenant_id, id) on delete cascade,
  foreign key (person_id) references person (id) on delete cascade,
  foreign key (couple_id) references couple (id) on delete cascade,
  foreign key (tenant_id, cohort_id) references cohort (tenant_id, id) on delete cascade
);

create index if not exists document_event_instance_id_idx
  on document (event_instance_id) where event_instance_id is not null;
create index if not exists document_event_series_id_idx
  on document (event_series_id) where event_series_id is not null;
create index if not exists document_cohort_id_idx
  on document (cohort_id) where cohort_id is not null;

create index if not exists document_node_document_ordering_idx
  on document_node (document_id, parent_id, ordering);

create index if not exists document_node_tag_node_id_idx
  on document_node_tag (node_id);
create index if not exists document_node_tag_person_id_idx
  on document_node_tag (person_id) where person_id is not null;
create index if not exists document_node_tag_couple_id_idx
  on document_node_tag (couple_id) where couple_id is not null;
create index if not exists document_node_tag_cohort_id_idx
  on document_node_tag (cohort_id) where cohort_id is not null;

drop trigger if exists _100_timestamps on document;
create trigger _100_timestamps before insert or update on document
  for each row execute function app_private.tg__timestamps();

drop trigger if exists _100_timestamps on document_node;
create trigger _100_timestamps before insert or update on document_node
  for each row execute function app_private.tg__timestamps();

alter table document enable row level security;
alter table document_node enable row level security;
alter table document_node_tag enable row level security;

